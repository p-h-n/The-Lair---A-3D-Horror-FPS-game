/*Function for BFS pathfinding is moved to its own file. This allows 
for easier trouble shooting and cleaning up the main.js file. */
export function findNextStep(seeker, target, grid){
     if(!grid[seeker.r] || !grid[target.r] || 
        grid[seeker.r][seeker.c] === undefined ||
         grid[target.r][target.c] === undefined){
return seeker;
    }
    const queue = [[seeker]];
    //a queue to manage the exploration of nodes that 
    //starts with the entities starting position(source node)
    const visited = new Set([`${seeker.r},${seeker.c}`]);
    //this prevents an infinite loop, remembering blocks that the seeker has visited.
    //A set stores the cells (row and collumn) elements 
    const direc = [[0, 1], [0, -1], [1,0], [-1, 0]];//north, east, south, west

    while(queue.length > 0){
        const path = queue.shift();
        const { r, c} = path[path.length - 1];
        /*as long as there is distance between the player and
        the seeker will continually hunt the player down.*/
        
        if(r === target.r && c === target.c){
            return path[1] || path[0];
            //victory condition returns path[0] as this is seeker's location.
            //path[1] makes it so that the seeker can get started again hunting the player
        }
        //if the seeker catches the player, the path is reset and the seeker seeks the player again
        for (let [dr, dc] of direc){
            const nr = r + dr;
            const nc = c + dc;
            if(grid[nr] && grid[nr][nc] === 0 && !visited.has(`${nr},${nc}`)){
                visited.add(`${nr},${nc}`);
                queue.push([...path, {r: nr,c: nc}]);
            }
            //check to see if the cube is able to go on the square. 
            //if the square is valid, it is visited so no other path claims it.
            //new square added to the end and it is pushed to the back of the queue
        }
    }
    /* This is a check to see if areas of the maze are unreachable, which shouldn't be 
    possible since the maze is generated by an algorithm. So it's kinda useless now. */
    if (!seeker.lastFailTarget || seeker.lastFailTarget !== target) {
        console.warn("Path unreachable. Standing still.");
        seeker.lastFailTarget = target;
    }
    return seeker;
    /* The Seeker doesn't move and remains still. */
}